import { apiRequest } from "./apiClient";

const b = (path, options = {}) => apiRequest(path, { role: "business", ...options });
const id = (value) => encodeURIComponent(value);
export const businessApi = {
  signup: (body) => apiRequest("/business/auth/signup", { method: "POST", body }),
  login: (body) => apiRequest("/business/auth/login", { method: "POST", body }),
  authProfile: () => b("/business/auth/profile"),
  updateAuthProfile: (body) => b("/business/auth/profile", { method: "PUT", body }),
  changePassword: (body) => b("/business/auth/password", { method: "PATCH", body }),
  profile: () => b("/business/profile"),
  saveProfile: (body) => b("/business/profile", { method: "PUT", body }),
  documents: () => b("/business/documents"),
  submitDocument: (formData) => b("/business/documents", { method: "POST", body: formData }),
  documentDownload: (documentId) => b(`/business/documents/${id(documentId)}/download`),
  uploadTurfImages: (formData) => b("/business/turfs/upload", { method: "POST", body: formData }),
  staff: () => b("/business/staff"),
  addStaff: (body) => b("/business/staff", { method: "POST", body }),
  updateStaff: (staffId, body) => b(`/business/staff/${id(staffId)}`, { method: "PATCH", body }),
  removeStaff: (staffId) => b(`/business/staff/${id(staffId)}`, { method: "DELETE" }),
  turfs: (query) => b("/business/turfs", { query }),
  createTurf: (body) => b("/business/turfs", { method: "POST", body }),
  updateTurf: (turfId, body) => b(`/business/turfs/${id(turfId)}`, { method: "PUT", body }),
  deleteTurf: (turfId) => b(`/business/turfs/${id(turfId)}`, { method: "DELETE" }),
  bookings: (query) => b("/business/bookings", { query }),
  bookingStats: (query) => b("/business/booking-stats", { query }),
  updateBooking: (bookingId, body) => b(`/business/bookings/${id(bookingId)}`, { method: "PATCH", body }),
  respondToReview: (reviewId, body) => b(`/business/reviews/${id(reviewId)}/response`, { method: "PATCH", body }),
  analytics: (query) => b("/analytics/business", { query }),
  financialStatement: (query) => b("/financials/business/statement", { query }),
  settlements: (query) => b("/financials/business/settlements", { query }),
  payouts: (query) => b("/financials/business/payouts", { query }),
  subscriptionCheckout: (body) => b("/subscriptions/checkout", { method: "POST", body, idempotent: true }),
  verifySubscription: (body) => b("/subscriptions/verify", { method: "POST", body, idempotent: true }),
  plans: () => b("/subscriptions/plans"),
  startTrial: (body) => b("/subscriptions/trial", { method: "POST", body }),
  activateFreePlan: (body) => b("/subscriptions/free", { method: "POST", body }),
  subscription: () => b("/subscriptions/me"),
  cancelSubscription: (body = {}) => b("/subscriptions/cancel", { method: "POST", body }),
  invoices: (query) => b("/invoices/me", { query }),
  notifications: (query) => b("/notifications", { query }),
  markNotificationRead: (notificationId) => b(`/notifications/${id(notificationId)}/read`, { method: "PATCH" }),
  notificationPreferences: () => b("/notifications/preferences"),
  updateNotificationPreferences: (body) => b("/notifications/preferences", { method: "PATCH", body }),
  createSupportTicket: (body) => b("/support", { method: "POST", body }),
  supportTickets: (query) => b("/support", { query }),
  supportTicket: (ticketId) => b(`/support/${id(ticketId)}`),
  replyToSupportTicket: (ticketId, body) => b(`/support/${id(ticketId)}/replies`, { method: "POST", body }),
};
